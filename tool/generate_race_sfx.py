#!/usr/bin/env python3
"""Generate the Puzzle Race sounds with the ElevenLabs Sound Generation API.

Writes ``assets/sfx/race_<name>.mp3``. ``assets/sfx/`` is already a registered
asset directory, so no pubspec change is needed. The app loads these on demand
when a race warms up (``AudioPlayerService.loadRaceAssets``), never at start.

The set is one family with the board's wooden piece sounds and the felt-mallet
/ glass classification sounds (``tool/generate_classification_sfx.py``, whose
finishing helpers this reuses): dry wood and felt for the clock, warm glass for
the rewards, a low wooden heartbeat for the pressure.

  countdown_beat   tight low tick, played for 3-2-1 (the "1" a touch higher)
  go               sharp start hit, clack plus glass ring
  correct          quick bright success blip
  correct_streak   the same blip layered a fifth and an octave up (streak >= 3)
  wrong            short dull buzz-thud, disappointed, never harsh
  level_up         short upward whoosh into a chime
  tension_loop     seamless 3.2 s heartbeat bed, looped under the race
  last_life        one heavier, lower heartbeat accent
  finish           resolving final hit
  new_best         short triumphant flourish

Two steps. The API generates SOURCE takes (``TAKES``); the shipped sounds
(``SHIPPED``) are built from the chosen takes, most from one take trimmed and
levelled, some layered from several:

* ``correct_streak`` is the ``correct`` take stacked a fifth and an octave up,
  so the streak sound is literally the brighter version of the plain one.
* The heartbeat is not the model's: its heartbeats are sub-bass only (nothing
  on a phone speaker) and it cannot hold a tempo. Each beat is the countdown
  tick pitched down and muffled into a lub-dub, over a short sub thump from
  the ``heartbeat`` take for headphones. ``last_life`` is that beat, lower and
  closer. So the race's pulse is made of the same wood as its countdown.
* ``tension_loop`` places four of those beats at an exact 75 bpm and sums them
  circularly (a tail that runs past the end wraps round to the start), which
  makes the seam sample-exact. The wrap sits just before a beat, where the
  previous tail has decayed. The encoded mp3 carries the LAME gapless header,
  which SoLoud's dr_mp3 honours, so the decoded loop is exactly its length.

Key handling: the key is read from ``ELEVENLABS_API_KEY`` or, with
``--key-file``, from a JSON/JSONC file containing an ``"ELEVENLABS_API_KEY"``
entry (the git-ignored ``opencode.jsonc``). It is never taken from argv, never
printed, and scrubbed from any error body before that is shown.

    # Generate every source take and build every sound.
    python3 tool/generate_race_sfx.py --key-file opencode.jsonc --force
    # Audition: three raw takes of two sources into build/race_sfx_takes.
    python3 tool/generate_race_sfx.py --key-file opencode.jsonc \\
        --only go,heartbeat --variants 3
    # Pick takes (repeatable); every sound using them is rebuilt.
    python3 tool/generate_race_sfx.py \\
        --choose go build/race_sfx_takes/race_go_v2.mp3
    # Rebuild everything from the chosen takes, no API calls.
    python3 tool/generate_race_sfx.py --build

Chosen takes live in ``build/race_sfx_takes/chosen`` (git-ignored). Every
finished file peaks at or below -3 dBFS (needs ffmpeg).
"""

