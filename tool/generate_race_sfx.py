# ElevenLabs.


def _generate(key: str, name: str, take: Take) -> bytes:
    text = f"{take.prompt}. {_STYLE}."
    if len(text) > _MAX_TEXT:
        raise ValueError(f"{name}: prompt is {len(text)} > {_MAX_TEXT} chars")
    body = json.dumps({
        "text": text,
        "duration_seconds": take.duration,
        "prompt_influence": take.influence,
        "model_id": MODEL_ID,
    }).encode("utf-8")
    request = urllib.request.Request(
        f"{API_URL}?output_format={OUTPUT_FORMAT}",
        data=body,
        method="POST",
        headers={
            "xi-api-key": key,
            "Content-Type": "application/json",
            "Accept": "audio/mpeg",
        },
    )
    with urllib.request.urlopen(request, timeout=120) as response:
        data = response.read()
        content_type = response.headers.get("Content-Type", "")
    if "audio" not in content_type and not data.startswith((b"ID3", b"\xff")):
        raise ValueError(
            f"{name}: expected audio, got {content_type or 'no content type'}"
        )
    if len(data) < 1024:
        raise ValueError(f"{name}: suspiciously small response ({len(data)} B)")
    return data


