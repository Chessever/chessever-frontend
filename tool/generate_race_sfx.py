@dataclass(frozen=True)
class Take:
    """A source generated by the API."""

    prompt: str
    duration: float  # asked of the API (0.5 s and up)
    influence: float


@dataclass(frozen=True)
class Layer:
    """One voice of a shipped sound, cut from a source take."""

    source: str
    start: float = 0.0  # seconds into the sound
    ratio: float = 1.0  # pitch ratio, tape style (1.5 = a fifth up)
    gain: float = 1.0
    # Fade the voice out between these times (seconds from its start).
    release: tuple[float, float] | None = None
    # Start this many ms before the source's loudest transient instead of at
    # its first audible sample (cuts a slow swell down to a short lead-in).
    align_to_peak_ms: float | None = None
    lowpass_hz: float | None = None  # muffles the voice (4-pole)
    highpass_hz: float | None = None  # drops rumble that eats headroom
    seconds: float | None = None  # use only this much of the source
    # Soft saturation (tanh) before the filters: grows harmonics above a low
    # fundamental, so a thud a phone speaker cannot reproduce is still heard
    # (the missing-fundamental trick). 1 = clean.
    drive: float = 1.0


@dataclass(frozen=True)
class LoopSpec:
    """Places the built sound as the beats of a seamless loop."""

    period: float  # seconds between beats
    beats: tuple[tuple[float, float], ...]  # (gain, pitch ratio) per beat
    offset: float  # first beat's start; the seam sits just before it


@dataclass(frozen=True)
class Shipped:
    """A file in ``assets/sfx``: layers mixed, capped, faded and levelled."""

    layers: tuple[Layer, ...]
    max_seconds: float  # hard cap (for a loop: one beat's length)
    rms_db: float  # target RMS; the -3 dBFS peak ceiling wins when lower
    highpass_hz: float | None = None  # on the whole mix
    # Pull the loudest transient down this far before levelling, so a sharp
    # click does not hold the body of the sound under the peak ceiling.
    limit_db: float = 0.0
    tail_fade: float = 0.06  # seconds of smooth fade before the cap
    loop: LoopSpec | None = None

    @property
    def sources(self) -> set[str]:
        return {layer.source for layer in self.layers}


