def _lub_dub(depth: float, weight: float) -> tuple[Layer, ...]:
    """One heartbeat: the countdown tick pitched down by [depth] and muffled,
    lub then a softer dub 0.2 s later, each over a short sub thump."""
    tick = {"lowpass_hz": 1600.0, "align_to_peak_ms": 3.0, "seconds": 0.3}
    # The thump is only weight under the tick: its beater click is filtered
    # out so the loop never clicks on every beat.
    thump = {"highpass_hz": 35.0, "lowpass_hz": 500.0}
    return (
        Layer("countdown_beat", 0.0, 0.75 * depth, 1.0, **tick),
        Layer("heartbeat", 0.0, 1.0 * depth, 0.8 * weight,
              release=(0.14, 0.32), **thump),
        Layer("countdown_beat", 0.2, 0.84 * depth, 0.55, **tick),
        Layer("heartbeat", 0.2, 1.1 * depth, 0.4 * weight,
              release=(0.10, 0.28), **thump),
    )


