# Finishing (mono float lists at 44.1 kHz, plain Python).


def _trim(
    samples: list[float],
    *,
    max_seconds: float | None = None,
    align_to_peak_ms: float | None = None,
) -> list[float]:
    """Drops lead-in and tail silence (relative to the take's own peak: the
    API's masters differ by ~25 dB), optionally starting a few ms before the
    loudest transient."""
    peak_level = max((abs(s) for s in samples), default=0.0)
    floor = peak_level * 10 ** (_SILENCE_DB / 20)
    audible = [i for i, s in enumerate(samples) if abs(s) > floor]
    if not audible:
        return samples
    start = max(0, audible[0] - round(_PRE_ROLL_S * SAMPLE_RATE))
    if align_to_peak_ms is not None:
        peak = max(range(len(samples)), key=lambda i: abs(samples[i]))
        lead = round(align_to_peak_ms / 1000 * SAMPLE_RATE)
        start = max(start, peak - lead)
    end = audible[-1] + 1
    if max_seconds is not None:
        end = min(end, start + round(max_seconds * SAMPLE_RATE))
    return samples[start:end]


def _biquad(samples: list[float], hz: float, *, high: bool) -> list[float]:
    """RBJ cookbook 2-pole Butterworth low/high-pass."""
    w0 = 2 * math.pi * hz / SAMPLE_RATE
    alpha = math.sin(w0) / (2 * math.sqrt(0.5))
    cos_w0 = math.cos(w0)
    if high:
        b0, b1, b2 = (1 + cos_w0) / 2, -(1 + cos_w0), (1 + cos_w0) / 2
    else:
        b0, b1, b2 = (1 - cos_w0) / 2, 1 - cos_w0, (1 - cos_w0) / 2
    a0, a1, a2 = 1 + alpha, -2 * cos_w0, 1 - alpha
    b0, b1, b2, a1, a2 = b0 / a0, b1 / a0, b2 / a0, a1 / a0, a2 / a0
    out: list[float] = []
    x1 = x2 = y1 = y2 = 0.0
    for x in samples:
        y = b0 * x + b1 * x1 + b2 * x2 - a1 * y1 - a2 * y2
        out.append(y)
        x2, x1, y2, y1 = x1, x, y1, y
    return out


def _filtered(
    samples: list[float], low: float | None, high: float | None
) -> list[float]:
    if high is not None:
        samples = _biquad(samples, high, high=True)
    if low is not None:  # two stages: a steep, click-free muffle
        samples = _biquad(_biquad(samples, low, high=False), low, high=False)
    return samples


def _fade(samples: list[float], tail: float) -> list[float]:
    """2 ms fade-in (a peak-aligned start can land mid-waveform) and a
    smooth [tail]-second fade-out, so a cap never ends on a cliff."""
    out = list(samples)
    fade_in = min(len(out), round(0.002 * SAMPLE_RATE))
    for i in range(fade_in):
        out[i] *= i / fade_in
    fade_out = min(len(out) // 2, round(tail * SAMPLE_RATE))
    for i in range(fade_out):
        out[len(out) - fade_out + i] *= 1 - _smoothstep(i / fade_out)
    return out


def _saturate(samples: list[float], drive: float) -> list[float]:
    """tanh soft clip, driven relative to the take's own peak and scaled back
    so the peak stays where it was."""
    peak = max(abs(s) for s in samples) or 1.0
    norm = math.tanh(drive)
    return [math.tanh(drive * s / peak) / norm * peak for s in samples]


def _limit(samples: list[float], reduce_db: float) -> list[float]:
    """Lookahead peak limiter: the loudest peak comes down by [reduce_db].
    Gain ramps down over 1.5 ms ahead of each peak (so no step lands on a
    transient) and recovers over 60 ms."""
    if reduce_db <= 0:
        return samples
    peak = max(abs(s) for s in samples)
    ceiling = peak * 10 ** (-reduce_db / 20)
    need = [min(1.0, ceiling / abs(s)) if abs(s) > ceiling else 1.0
            for s in samples]
    ahead = max(1, round(0.0015 * SAMPLE_RATE))
    n = len(samples)
    # Sliding minimum of the needed gain over the next 2 * ahead samples.
    window = 2 * ahead
    lowest = [1.0] * n
    queue: deque[int] = deque()
    for j in range(n + window):
        if j < n:
            while queue and need[queue[-1]] >= need[j]:
                queue.pop()
            queue.append(j)
        i = j - window
        if i >= 0:
            while queue and queue[0] < i:
                queue.popleft()
            lowest[i] = need[queue[0]]
    # Moving average over [i - ahead, i]: a ramp that still never exceeds the
    # gain a peak needs (every value averaged at the peak is at most it).
    gains = [1.0] * n
    running = 0.0
    for i in range(n):
        running += lowest[i]
        if i > ahead:
            running -= lowest[i - ahead - 1]
        gains[i] = running / min(i + 1, ahead + 1)
    release = 1 - math.exp(-1 / (0.06 * SAMPLE_RATE))
    out: list[float] = []
    gain = 1.0
    for i, sample in enumerate(samples):
        gain = min(gains[i], gain + (1 - gain) * release)
        out.append(sample * gain)
    return out


def _stats(samples: list[float]) -> str:
    rms = math.sqrt(sum(s * s for s in samples) / max(len(samples), 1))
    peak = max(abs(s) for s in samples)
    return (
        f"{len(samples) / SAMPLE_RATE:.3f}s, rms {_db(rms):.1f} dB, "
        f"peak {_db(peak):.1f} dB"
    )


def _mix(
    layers: tuple[Layer, ...], sources: dict[str, list[float]]
) -> list[float]:
    voices: list[tuple[int, list[float]]] = []
    for layer in layers:
        source = _trim(
            sources[layer.source],
            max_seconds=layer.seconds,
            align_to_peak_ms=layer.align_to_peak_ms,
        )
        if layer.seconds is not None:
            source = _fade(source, min(0.08, layer.seconds / 3))
        if layer.drive != 1.0:
            source = _saturate(source, layer.drive)
        source = _filtered(source, layer.lowpass_hz, layer.highpass_hz)
        note = Note(0.0, layer.ratio, gain=layer.gain, release=layer.release)
        voices.append((round(layer.start * SAMPLE_RATE), _render(source, note)))
    length = max(offset + len(voice) for offset, voice in voices)
    mix = [0.0] * length
    for offset, voice in voices:
        for i, sample in enumerate(voice):
            mix[offset + i] += sample
    return mix


def _loop(beat: list[float], spec: LoopSpec) -> list[float]:
    """Circular sum of the beats: sample-exact seam, exact tempo."""
    length = round(spec.period * len(spec.beats) * SAMPLE_RATE)
    mix = [0.0] * length
    for index, (gain, ratio) in enumerate(spec.beats):
        voice = _render(beat, Note(0.0, ratio, gain=gain))
        start = round((spec.offset + index * spec.period) * SAMPLE_RATE)
        for i, sample in enumerate(voice):
            mix[(start + i) % length] += sample
    return mix


def _seam_jump(samples: list[float]) -> float:
    """The step across the wrap relative to the loop's typical step (1 is as
    smooth as anywhere else in the loop)."""
    steps = [abs(samples[i + 1] - samples[i]) for i in range(len(samples) - 1)]
    typical = sum(steps) / len(steps)
    return abs(samples[0] - samples[-1]) / max(typical, 1e-9)


def _decoded_frames(path: Path) -> int:
    """Frames ffmpeg decodes; it honours the LAME gapless header as SoLoud's
    dr_mp3 does."""
    result = subprocess.run(
        [
            "ffmpeg", "-hide_banner", "-nostats", "-i", str(path),
            "-f", "s16le", "-ac", "1", "-",
        ],
        capture_output=True,
        check=True,
    )
    return len(result.stdout) // 2


def build(name: str, tmp: Path) -> str:
    """Builds ``assets/sfx/race_<name>.mp3`` from the chosen takes."""
    spec = SHIPPED[name]
    sources = {
        source: _decode(CHOSEN_DIR / f"race_{source}.mp3", tmp)
        for source in spec.sources
    }
    samples = _mix(spec.layers, sources)
    if spec.highpass_hz is not None:
        samples = _filtered(samples, None, spec.highpass_hz)
    samples = _trim(samples, max_seconds=spec.max_seconds)
    samples = _fade(_limit(samples, spec.limit_db), spec.tail_fade)
    target = OUT_DIR / f"race_{name}.mp3"
    if spec.loop is None:
        samples = _level(samples, spec.rms_db)
        _encode(samples, target, tmp)
        return f"ok    race_{name}.mp3 {_stats(samples)}"
    samples = _level(_loop(samples, spec.loop), spec.rms_db)
    _encode(samples, target, tmp)
    decoded = _decoded_frames(target)
    gapless = (
        "gapless"
        if decoded == len(samples)
        else f"NOT GAPLESS: decodes {decoded} of {len(samples)} frames"
    )
    return (
        f"ok    race_{name}.mp3 {_stats(samples)}, seam "
        f"{_seam_jump(samples):.2f}x typical step, {gapless}"
    )


def build_all(names: list[str]) -> int:
    if shutil.which("ffmpeg") is None:
        print("ffmpeg is required to build the race sounds", file=sys.stderr)
        return 2
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    failures = 0
    with tempfile.TemporaryDirectory() as tmp_dir:
        for name in names:
            missing = [
                s for s in sorted(SHIPPED[name].sources)
                if not (CHOSEN_DIR / f"race_{s}.mp3").exists()
            ]
            if missing:
                failures += 1
                print(f"skip  race_{name}.mp3 (no chosen take: {missing})")
                continue
            print(build(name, Path(tmp_dir)))
    return 1 if failures else 0


def _choose(source: str, take: Path) -> None:
    CHOSEN_DIR.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(take, CHOSEN_DIR / f"race_{source}.mp3")


# ---------------------------------------------------------------------------


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--only",
        help="comma-separated source takes to generate (default: all)",
    )
    parser.add_argument(
        "--force",
        action="store_true",
        help="regenerate sources that already have a chosen take",
    )
    parser.add_argument(
        "--key-file",
        help="JSON/JSONC file holding an ELEVENLABS_API_KEY entry",
    )
    parser.add_argument(
        "--variants",
        type=int,
        default=1,
        help="takes per source; >1 writes raw takes to --raw-dir to audition",
    )
    parser.add_argument(
        "--raw-dir",
        default=str(RAW_DIR),
        help="where raw takes go when --variants > 1",
    )
    parser.add_argument(
        "--choose",
        nargs=2,
        action="append",
        metavar=("SOURCE", "TAKE"),
        help="use TAKE for SOURCE and rebuild what uses it (repeatable)",
    )
    parser.add_argument(
        "--build",
        action="store_true",
        help="rebuild every sound from the chosen takes (no API calls)",
    )
    args = parser.parse_args()

    if args.choose:
        chosen: set[str] = set()
        for source, take in args.choose:
            source = source.strip().removeprefix("race_")
            if source not in TAKES:
                print(f"unknown source: {source}", file=sys.stderr)
                return 2
            _choose(source, Path(take))
            chosen.add(source)
        return build_all(_dependents(chosen))

    if args.build:
        return build_all(list(SHIPPED))

    key = _read_key(args.key_file)
    if not key:
        print(
            "No ElevenLabs key: set ELEVENLABS_API_KEY or pass --key-file",
            file=sys.stderr,
        )
        return 2

    names = list(TAKES)
    if args.only:
        names = [n.strip().removeprefix("race_") for n in args.only.split(",")]
        unknown = [n for n in names if n not in TAKES]
        if unknown:
            print(f"unknown source(s): {', '.join(unknown)}", file=sys.stderr)
            return 2

    raw_dir = Path(args.raw_dir)
    if args.variants > 1:
        raw_dir.mkdir(parents=True, exist_ok=True)

    failures = 0
    generated: set[str] = set()
    for name in names:
        if (
            args.variants == 1
            and not args.force
            and (CHOSEN_DIR / f"race_{name}.mp3").exists()
        ):
            print(f"skip  {name} (chosen take exists; --force to regenerate)")
            continue
        for take_index in range(1, args.variants + 1):
            label = f"race_{name}" + (
                f"_v{take_index}" if args.variants > 1 else ""
            )
            try:
                data = _generate(key, name, TAKES[name])
            except urllib.error.HTTPError as error:
                failures += 1
                detail = error.read()[:200].decode("utf-8", "replace")
                detail = detail.replace(key, "***")  # never echo the key back
                print(f"FAIL  {label} HTTP {error.code}: {detail}")
                continue
            except (urllib.error.URLError, ValueError, TimeoutError) as error:
                failures += 1
                message = str(error).replace(key, "***")
                print(f"FAIL  {label} {type(error).__name__}: {message}")
                continue
            if args.variants > 1:
                path = raw_dir / f"{label}.mp3"
                path.write_bytes(data)
                print(f"take  {path} {len(data)} B")
            else:
                CHOSEN_DIR.mkdir(parents=True, exist_ok=True)
                (CHOSEN_DIR / f"race_{name}.mp3").write_bytes(data)
                generated.add(name)
            time.sleep(0.4)  # stay well under the per-second request limit

    if generated:
        failures += build_all(_dependents(generated))
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
