-- The Lichess and Chess.com usernames ChessEver knows for FIDE players.
-- My Prep reads them to prefill a player's sources when the reader adds that
-- player, so nobody types a known handle. Additive: one new table, one new
-- policy, nothing existing is changed.
--
-- Edited by hand (Table editor or SQL), service_role only: add a row to
-- publish a handle, delete one to withdraw it. Apps read the whole list and
-- follow it, so a change shows the next time My Prep is opened.

begin;

create table public.player_online_accounts (
  -- chess_players.fideid. Not a foreign key: a handle may be published a
  -- little before its player's row is, and a rating import must never be
  -- blocked by this table.
  fide_id bigint not null,
  platform text not null,
  username text not null,
  created_at timestamptz not null default now(),
  constraint player_online_accounts_fide_id_positive check (fide_id > 0),
  constraint player_online_accounts_platform_known check (
    platform in ('lichess', 'chesscom')
  ),
  constraint player_online_accounts_username_shape check (
    username ~ '^[A-Za-z0-9_-]{2,40}$'
  )
);

comment on table public.player_online_accounts is
  'Public online handles of FIDE players, curated by ChessEver. A player may have several per platform.';

-- Both sites treat names without case, and a handle is one person's.
create unique index player_online_accounts_handle_key
  on public.player_online_accounts (platform, lower(username));
create index player_online_accounts_fide_idx
  on public.player_online_accounts (fide_id);

alter table public.player_online_accounts enable row level security;

create policy player_online_accounts_public_read
  on public.player_online_accounts for select to anon, authenticated
  using (true);

-- Do not inherit any broad Supabase default table privileges.
revoke all on public.player_online_accounts from public, anon, authenticated, service_role;
grant select on public.player_online_accounts to anon, authenticated;
grant select, insert, update, delete on public.player_online_accounts to service_role;

